	function refreshTableOfContents() {
		console.log("Refreshing Table of contents. Removing elements")
		const toc_uls = document.querySelectorAll('.toc-ul')  // need to update two places
		toc_uls.forEach( toc_ul => {
			toc_ul.replaceChildren() // delete all existing li elements
		});
		generateTableOfContents()
	}

