				headers.forEach(h_el => {
					if ( ["h1", "h2", "h3", "h4"].indexOf(h_el.tagName.toLowerCase()) > -1 ) {
						if ( h_el.id ) {
							const padding_class = `${h_el.tagName.toLowerCase()}-toc-padding`;
